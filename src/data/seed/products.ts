const img = (keywords: string, lock: number) =>
  `https://loremflickr.com/800/600/${keywords}/all?lock=${lock}`;

type ProductSeed = Partial<Product> &
  Pick<Product, "slug" | "title" | "description" | "priceCents"> & {
    merchantSlug: string;
    category: string;
  };

let order = 0;
function product(seed: ProductSeed): Product {
  const { merchantSlug, ...rest } = seed;
  order += 1;
  return {
    id: sid.product(merchantSlug, seed.slug),
    merchantId: sid.merchant(merchantSlug),
    currency: "USD",
    images: [],
    inventoryStatus: "in_stock",
    variantGroups: [],
    attributes: {},
    tags: [],
    fulfillmentTypes: ["delivery", "pickup"],
    leadTime: { minutesMin: 20, minutesMax: 40 },
    featured: false,
    sortOrder: order,
    active: true,
    ...rest,
  };
}

const sizes = (ids: string[]): VariantGroup => ({
  id: "size",
  name: "Size",
  required: true,
  options: ids.map((s) => ({ id: s.toLowerCase(), name: s, priceDeltaCents: 0 })),
});

