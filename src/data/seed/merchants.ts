type MerchantSeed = Omit<Merchant, "id" | "createdAt" | "updatedAt" | "images" | "ratingCount"> & { images?: string[]; ratingCount?: number };

function merchant(seed: MerchantSeed): Merchant {
  return {
    ...seed,
    id: sid.merchant(seed.slug),
    images: seed.images ?? [],
    ratingCount: seed.ratingCount ?? 0,
    createdAt: SEEDED_AT,
    updatedAt: SEEDED_AT,
  };
}

